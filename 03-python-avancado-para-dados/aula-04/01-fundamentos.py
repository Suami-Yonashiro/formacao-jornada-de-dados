def imprimir_itens(lista):
    for item in lista:
        print(item)


l1 = [1, 2, 3, 4, 5, 6]
print("\nImprimir itens da lista l1:")
imprimir_itens(l1)

l2 = ["Luiza", "Luciano", "Caio", "Michelle"]
print("\nImprimir itens da lista l2:")
imprimir_itens(l2)

l3 = [12, "Luiza", 2512.24, True]
print("\nImprimir itens da lista l3:")
imprimir_itens(l3)
